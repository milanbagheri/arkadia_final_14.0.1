'use strict';
const assert=require('assert');
const {createWorld,submitAction,resolveTurn}=require('../lib/turn-engine');
const countries=Array.from({length:258},(_,i)=>({owner:i,army:100,industry:10,cash:100,stance:.5,fatigue:0}));
const w=createWorld(countries),active=[0,1,2,3];
assert.equal(submitAction(w,0,{type:'invest',amount:10},0,active).ready,1);
assert.throws(()=>submitAction(w,0,{type:'pass'},0,active),/already_submitted/);
assert.equal(w.countries[0].cash,100,'action must not mutate world before resolution');
assert.equal(submitAction(w,1,{type:'recruit',amount:5},0,active).ready,2);
assert.equal(submitAction(w,2,{type:'stance',value:.8},0,active).ready,3);
assert.equal(submitAction(w,3,{type:'pass'},0,active).ready,4);
const result=resolveTurn(w,active);
assert.equal(result.turn,1);assert.equal(w.countries[0].industry,10.1);assert.equal(w.countries[0].cash,170.8);
assert.equal(w.countries[1].army,105);assert.equal(w.countries[1].cash,170);
assert.equal(w.countries[2].stance,.8);
assert.throws(()=>submitAction(w,0,{type:'invest',amount:1},0,active),/stale_turn/);
assert.throws(()=>submitAction(w,4,{type:'pass'},1,active),/not_active_player/);
assert.throws(()=>submitAction(w,0,{type:'recruit',amount:999999},1,active),/invalid_action/);
console.log('Stage 11 atomic turn-resolution tests passed.');
